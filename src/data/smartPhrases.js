export const getSmartPhrases = (jobTitle) => {
  if (!jobTitle) return smartPhrases["general"];
  
  const title = jobTitle.toLowerCase();
  
  // Try to find an exact match
  if (smartPhrases[title]) return smartPhrases[title];
  
  // Try partial matching
  const matchingKey = Object.keys(smartPhrases).find(key => 
    title.includes(key) || key.includes(title)
  );
  
  if (matchingKey) return smartPhrases[matchingKey];
  
  // Try some synonyms/keywords
  if (title.includes('dev') || title.includes('program') || title.includes('code')) return smartPhrases["software engineer"];
  if (title.includes('data')) return smartPhrases["data analyst"];
  if (title.includes('market') || title.includes('seo') || title.includes('content')) return smartPhrases["marketing manager"];
  if (title.includes('design') || title.includes('art')) return smartPhrases["graphic designer"];
  if (title.includes('sale') || title.includes('account') || title.includes('business')) return smartPhrases["sales executive"];
  
  // Fallback
  return smartPhrases["general"];
};
